CREATE TABLE auth_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code VARCHAR(5) NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL,
    CONSTRAINT uk_branches_branch_code UNIQUE (branch_code)
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100),
    marketing_consent BOOLEAN NOT NULL,
    auth_account_id BIGINT,
    CONSTRAINT uk_customers_phone UNIQUE (phone),
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT uk_customers_auth_account UNIQUE (auth_account_id),
    CONSTRAINT fk_customers_auth_account
        FOREIGN KEY (auth_account_id) REFERENCES auth_accounts (id)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id VARCHAR(20) NOT NULL,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    nic VARCHAR(20) NOT NULL,
    address VARCHAR(150),
    email VARCHAR(100),
    phone VARCHAR(20),
    position VARCHAR(30) NOT NULL,
    branch_id BIGINT NOT NULL,
    employment_status VARCHAR(20) NOT NULL,
    auth_account_id BIGINT,
    CONSTRAINT uk_employees_employee_id UNIQUE (employee_id),
    CONSTRAINT uk_employees_nic UNIQUE (nic),
    CONSTRAINT uk_employees_auth_account UNIQUE (auth_account_id),
    CONSTRAINT fk_employees_branch
        FOREIGN KEY (branch_id) REFERENCES branches (id),
    CONSTRAINT fk_employees_auth_account
        FOREIGN KEY (auth_account_id) REFERENCES auth_accounts (id)
);

CREATE TABLE employee_update_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_employee_id VARCHAR(20) NOT NULL,
    updated_by_employee_id VARCHAR(20) NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
